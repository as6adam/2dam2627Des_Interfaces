import { createRequire } from 'node:module'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { once } from 'node:events'
import assert from 'node:assert/strict'
import { createStaticServer, listen } from './static-server.mjs'

const { chromium } = createRequire(import.meta.url)(process.env.TEMPORA_PLAYWRIGHT_MODULE || 'playwright')
const server = createStaticServer('dist')
const port = await listen(server)
const base = `http://127.0.0.1:${port}`
const browser = await chromium.launch({ headless: true, ...(process.env.TEMPORA_CHROME_PATH ? { executablePath: process.env.TEMPORA_CHROME_PATH } : {}) })
const errors = []; const checks = []
const observe = (page) => page.on('pageerror', (e) => errors.push(String(e)))
const seed = (context) => context.addInitScript(() => {
  if (!localStorage.getItem('tempora-v1')) localStorage.setItem('tempora-v1', JSON.stringify({ version: 1, state: { items: [], purpose: 'academic', language: 'es', notifications: false, mode: 'light', theme: 'agate' } }))
})
await mkdir('test-results', { recursive: true })
try {
  const desktop = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce', acceptDownloads: true })
  await seed(desktop)
  const page = await desktop.newPage(); observe(page)
  await page.clock.install({ time: new Date() })
  await page.goto(`${base}/app/index.html`)
  await page.getByRole('button', { name: 'Añadir', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Asignatura', { exact: true }).fill('Redes e2e')
  const due = new Date(); due.setDate(due.getDate() + 8); due.setHours(9, 0, 0, 0)
  const date = `${due.getFullYear()}-${String(due.getMonth() + 1).padStart(2, '0')}-${String(due.getDate()).padStart(2, '0')}`
  await dialog.locator('input[type="date"]').fill(date)
  await dialog.getByRole('button', { name: 'Añadir', exact: true }).click()
  await page.getByRole('button', { name: /^Examen: Redes e2e/ }).click()
  await page.getByRole('button', { name: 'Planificación automática', exact: true }).click()
  await page.getByRole('button', { name: 'Generar propuesta', exact: true }).click()
  assert.match(await page.getByRole('dialog', { name: 'Planificación automática', exact: true }).innerText(), /4\/4/)
  await page.clock.runFor(1000)
  await page.screenshot({ path: 'test-results/planner-desktop.png' })
  await page.getByRole('button', { name: 'Añadir sesiones al calendario', exact: true }).click()
  let saved = await page.evaluate(() => JSON.parse(localStorage.getItem('tempora-v1')).state)
  assert.equal(saved.items.length, 5)
  checks.push('Automatic planner: four reviewed, linked sessions saved before the deadline')
  await page.getByRole('button', { name: /^Sesión de estudio: Redes e2e/ }).first().click()
  await page.getByRole('button', { name: 'Marcar como completado', exact: true }).click()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Iniciar', exact: true }).click()
  await page.clock.fastForward(25 * 60 * 1000 + 1000)
  const progress = await page.evaluate(() => JSON.parse(localStorage.getItem('tempora-progress-v1')).state)
  assert.equal(progress.focusLog.length, 1)
  assert.equal(progress.focusLog[0].minutes, 25)
  checks.push('Pomodoro: a completed focus cycle creates exactly one persisted 25-minute entry')
  await page.getByRole('button', { name: 'Estadísticas', exact: true }).click()
  assert.match(await page.getByRole('dialog', { name: 'Estadísticas', exact: true }).innerText(), /25/)
  for (let n = 0; n < 12; n++) {
    await page.keyboard.press('Tab')
    assert(await page.evaluate(() => !!document.activeElement?.closest('[role="dialog"]')), 'Tab focus stays inside the statistics dialog')
  }
  const cdp = await desktop.newCDPSession(page)
  await cdp.send('Accessibility.enable')
  const tree = await cdp.send('Accessibility.getFullAXTree')
  const buttons = tree.nodes.filter((n) => !n.ignored && n.role?.value === 'button')
  assert(buttons.length > 0 && buttons.every((n) => n.name?.value), 'Visible accessibility buttons have names')
  await page.clock.runFor(1000)
  await page.screenshot({ path: 'test-results/statistics-desktop.png' })
  await page.keyboard.press('Escape')
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  checks.push('Keyboard and accessibility tree: named buttons, modal focus trap and Escape')
  await page.getByRole('button', { name: 'Transferir datos', exact: true }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar archivo', exact: true }).click()
  const download = await downloadPromise
  const file = await readFile(await download.path())
  assert.equal(JSON.parse(file.toString()).app.items.length, 5)
  await page.keyboard.press('Escape')

  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1, reducedMotion: 'reduce' })
  await seed(mobile)
  await mobile.addInitScript(() => {
    class SimulatedKeyboardViewport extends EventTarget { height = 500; offsetTop = 0; scale = 1; width = 390 }
    Object.defineProperty(window, 'visualViewport', { configurable: true, value: new SimulatedKeyboardViewport() })
  })
  const phone = await mobile.newPage(); observe(phone)
  await phone.goto(`${base}/app/index.html`)
  await phone.getByRole('button', { name: 'Añadir', exact: true }).click()
  await phone.getByLabel('Asignatura', { exact: true }).fill('Teclado simulado')
  const box = await phone.getByRole('dialog').boundingBox()
  assert(box && box.y >= 0 && box.y + box.height <= 501, 'The dialog fits the 500px visual viewport')
  await phone.getByLabel('Notas', { exact: true }).fill('El contenido debe permanecer accesible con el teclado abierto.')
  await phone.getByRole('button', { name: 'Cancelar', exact: true }).click()
  checks.push('Virtual keyboard simulation: 390px phone, 500px visual viewport, editable form and reachable actions')
  await phone.getByRole('button', { name: 'Menú', exact: true }).click()
  await phone.getByRole('button', { name: 'Transferir datos', exact: true }).click()
  const input = phone.locator('input[type="file"]')
  for (let n = 0; n < 2; n++) {
    await input.setInputFiles({ name: 'tempora.json', mimeType: 'application/json', buffer: file })
    await phone.getByRole('button', { name: 'Importar y combinar', exact: true }).click()
    await phone.getByRole('status').filter({ hasText: 'Datos combinados correctamente' }).waitFor()
  }
  const imported = await phone.evaluate(() => ({ app: JSON.parse(localStorage.getItem('tempora-v1')).state, progress: JSON.parse(localStorage.getItem('tempora-progress-v1')).state }))
  assert.equal(imported.app.items.length, 5); assert.equal(imported.progress.focusLog.length, 1)
  assert.equal(Object.keys(imported.progress.completed).length, 1)
  const beforeBadFile = JSON.stringify(imported.app.items)
  await input.setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{invalid') })
  await phone.getByRole('alert').waitFor()
  await phone.waitForFunction(() => { const dialog = document.querySelector('[role="dialog"]'); return dialog && +getComputedStyle(dialog).opacity > .99 })
  assert.equal(await phone.evaluate(() => JSON.stringify(JSON.parse(localStorage.getItem('tempora-v1')).state.items)), beforeBadFile)
  await phone.screenshot({ path: 'test-results/transfer-mobile.png' })
  checks.push('Cross-device file transfer: isolated phone context, duplicate import, progress preserved, invalid file rejected')
  await phone.keyboard.press('Escape')
  await phone.goto(`${base}/#screenshots`)
  await phone.locator('#screenshots img').first().waitFor({ state: 'attached' })
  assert.equal(await phone.locator('#screenshots img').count(), 10)
  assert.equal(await phone.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  checks.push('Landing: ten screenshots and no horizontal overflow at 390px')
  assert.deepEqual(errors, [])
  await writeFile('test-results/browser-report.json', JSON.stringify({ version: '1.1.0', checks, errors, scope: 'Chromium desktop and touch emulation, simulated virtual keyboard and Chromium accessibility tree; not a physical screen-reader certification.' }, null, 2))
  console.log(checks.map((c) => `✓ ${c}`).join('\n'))
} finally {
  await browser.close()
  server.close()
  await once(server, 'close')
}
